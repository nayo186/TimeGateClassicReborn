// The files of a known edition
struct KnownEdition
{
    const KnownGameFile* files;
    size_t count;
};

// Every edition we know, in one list
inline const std::vector<KnownEdition>& knownEditions()
{
#define EDITION(files) KnownEdition{ files, sizeof(files) / sizeof(files[0]) }
    static const std::vector<KnownEdition> editions = {
        EDITION(kKnownAitd1), EDITION(kKnownJack), EDITION(kKnownAitd2), EDITION(kKnownAitd2Gog),
        EDITION(kKnownAitd3), EDITION(kKnownAitd3es), EDITION(kKnownTimeGate), EDITION(kKnownTimeGateEs), EDITION(kKnownTimeGateDe), EDITION(kKnownTimeGateIt),
        EDITION(kKnownTimeGateFr),
    };
#undef EDITION
    return editions;
}

// True if a file with this name (upper case), size and CRC-32 is in a known edition
inline bool isKnownGameFile(const std::string& name, unsigned int size, unsigned int crc)
{
    for (const KnownEdition& edition : knownEditions())
        for (size_t i = 0; i < edition.count; i++)
            if (edition.files[i].size == size && edition.files[i].crc == crc && name == edition.files[i].name)
                return true;
    return false;
}

// True if a known edition has a file with this name (upper case)
inline bool isKnownGameFileName(const std::string& name)
{
    for (const KnownEdition& edition : knownEditions())
        for (size_t i = 0; i < edition.count; i++)
            if (name == edition.files[i].name)
                return true;
    return false;
}
